# ---------------------------------------------------------------- ANSI -> HTML
DEFAULT_FG = (230, 237, 243)
SGR = re.compile(r"\x1b\[([0-9;]*)m")
USED = set()
PAIRS = set()  # (fg hex, bg hex) as drawn; no fg = the default, no bg = the page background


def hexof(rgb):
    return "%02X%02X%02X" % rgb


def glyphs(text):
    """Every cell is one character of the bundled DejaVu Sans Mono subset (assets/fonts), so all cells have the
    same advance. No per-glyph wrapper: an inline-block's width is floored to 1/64 px, which drifts a row."""
    return esc(text)


def screen(name, first=None, last=None):
    with open(os.path.join(GOLD, name), encoding="utf-8") as fh:
        lines = fh.read().split("\n")
    while lines and lines[-1] == "":
        lines.pop()
    lines = lines[(first or 1) - 1:(last or len(lines))]
    fg, bg, bold = None, None, False
    out = []
    for ln in lines:
        pos, segs, cur = 0, [], ""
        parts = []
        for m in SGR.finditer(ln):
            parts.append((ln[pos:m.start()], (fg, bg, bold)))
            pos = m.end()
            codes = [int(c) for c in m.group(1).split(";") if c != ""] or [0]
            i = 0
            while i < len(codes):
                c = codes[i]
                if c == 0:
                    fg, bg, bold = None, None, False
                elif c == 1:
                    bold = True
                elif c == 38 and codes[i + 1] == 2:
                    fg = tuple(codes[i + 2:i + 5]); i += 4
                elif c == 48 and codes[i + 1] == 2:
                    bg = tuple(codes[i + 2:i + 5]); i += 4
                i += 1
        parts.append((ln[pos:], (fg, bg, bold)))
        html = ""
        for text, (f_, b_, bo) in parts:
            if not text:
                continue
            cls = []
            PAIRS.add((hexof(f_ or DEFAULT_FG), hexof(b_) if b_ else "0D1117"))
            if f_ and f_ != DEFAULT_FG:
                cls.append("f" + hexof(f_)); USED.add(("f", hexof(f_)))
            if b_:
                cls.append("g" + hexof(b_)); USED.add(("g", hexof(b_)))
            if bo:
                cls.append("b")
            cells = glyphs(text)
            html += f'<span class="{" ".join(cls)}">{cells}</span>' if cls else cells
        out.append(f'<span class="r">{html}</span>')
    return "".join(out)


def _lum(rgb):
    def c(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = rgb
    return 0.2126 * c(r) + 0.7152 * c(g) + 0.0722 * c(b)


def _ratio(a, b):
    la, lb = _lum(a), _lum(b)
    if la < lb:
        la, lb = lb, la
    return (la + 0.05) / (lb + 0.05)


def _rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _lift(fg, bgs):
    """Blend towards white until fg reaches 4.5:1 on every background; keeps the hue and the ordering."""
    t = 0.0
    cur = fg
    while min(_ratio(cur, b) for b in bgs) < 4.5 and t < 1:
        t += 0.01
        cur = tuple(round(v + (255 - v) * t) for v in fg)
    return cur


CONTRAST = []  # (hex, before, after, new hex)


def screen_css():
    css = ["/* generated by tools/build.py from the golden .ansi files; foregrounds under 4.5:1 are lifted to 4.5:1 */", ".term .b{font-weight:700}"]
    for kind, h in sorted(USED):
        if kind == "g":
            fgs = [_rgb(f_) for f_, b in PAIRS if b == h]
            bg = _rgb(h)
            # dark text on a light fill (a pill): lift the fill until the text reads at 4.5:1
            if fgs and all(_lum(f_) < _lum(bg) for f_ in fgs) and min(_ratio(f_, bg) for f_ in fgs) < 4.5:
                nb = _lift(bg, [(0, 0, 0)])
                while min(_ratio(f_, nb) for f_ in fgs) < 4.5:
                    nb = tuple(min(255, v + 3) for v in nb)
                CONTRAST.append(("bg " + h, min(_ratio(f_, bg) for f_ in fgs), min(_ratio(f_, nb) for f_ in fgs), hexof(nb)))
                css.append(f".term .g{h}{{background:#{hexof(nb)}}}")
            else:
                css.append(f".term .g{h}{{background:#{h}}}")
            continue
        fg = _rgb(h)
        bgs = [_rgb(b) for f_, b in PAIRS if f_ == h]
        before = min(_ratio(fg, b) for b in bgs)
        dark_on_light = all(_lum(fg) < _lum(b) for b in bgs)
        new = _lift(fg, bgs) if before < 4.5 and not dark_on_light else fg
        after = min(_ratio(new, b) for b in bgs)
        CONTRAST.append((h, before, after, hexof(new)))
        css.append(f".term .f{h}{{color:#{hexof(new)}}}")
    return "\n".join(css)


