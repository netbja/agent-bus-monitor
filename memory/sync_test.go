package memory_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/netbja/agent-bus-monitor/memory"
	"github.com/netbja/agent-bus-monitor/memory/memtest"
)

func read(t *testing.T, root, rel string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestRenderBlockRebasesLinks(t *testing.T) {
	index := "# Shared memory — x\n\nIntro.\n\n- [P](PROTOCOL.md)\n- [W](./PROTOCOL.md#writing)\n- [L](lessons/a.md)\n" +
		"- [U](https://x.y/z.md)\n- [A](#top)\n![d](img/d.png)\n"
	got := memory.RenderBlock(index)
	for _, want := range []string{
		"(docs/memory/PROTOCOL.md)", "(docs/memory/PROTOCOL.md#writing)", "(docs/memory/lessons/a.md)",
		"(https://x.y/z.md)", "(#top)", "(docs/memory/img/d.png)",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("block lacks %s:\n%s", want, got)
		}
	}
	if strings.Contains(got, "# Shared memory") {
		t.Errorf("the title heading was kept:\n%s", got)
	}
	if !strings.HasPrefix(got, memory.BeginMarker+"\n<!-- Generated by `agentbus mem sync` from docs/memory/INDEX.md. Edit the index, not this block. -->\n\nIntro.\n") ||
		!strings.HasSuffix(got, "![d](docs/memory/img/d.png)\n"+memory.EndMarker) {
		t.Errorf("layout:\n%q", got)
	}
}

func TestSyncIsIdempotent(t *testing.T) {
	root := memtest.WriteTree(t)
	before := read(t, root, "AGENTS.md")
	changed, err := memory.Sync(root)
	if err != nil || changed || read(t, root, "AGENTS.md") != before {
		t.Fatalf("second sync: changed %v err %v", changed, err)
	}
}

func TestSyncKeepsOutsideText(t *testing.T) {
	root := memtest.WriteTree(t)
	head, tail := "# Title\r\nkeep me  \n\n", "\n## After\nalso kept\n"
	memtest.Write(t, root, "AGENTS.md", head+memory.BeginMarker+"\nhand edit\n"+memory.EndMarker+tail)
	changed, err := memory.Sync(root)
	got := read(t, root, "AGENTS.md")
	if err != nil || !changed || !strings.HasPrefix(got, head+memory.BeginMarker) || !strings.HasSuffix(got, memory.EndMarker+tail) || strings.Contains(got, "hand edit") {
		t.Fatalf("changed %v err %v:\n%q", changed, err, got)
	}
}

func TestSyncMissingMarkers(t *testing.T) {
	root := memtest.WriteTree(t)
	for _, body := range []string{"no markers\n", memory.BeginMarker + "\nonly begin\n", memory.EndMarker + "\n" + memory.BeginMarker + "\n"} {
		memtest.Write(t, root, "AGENTS.md", body)
		if _, err := memory.Sync(root); err == nil || read(t, root, "AGENTS.md") != body {
			t.Errorf("%q: err %v, file %q", body, err, read(t, root, "AGENTS.md"))
		}
	}
}

func TestCheckBlockDrift(t *testing.T) {
	root := memtest.WriteTree(t)
	memtest.Append(t, root, "docs/memory/INDEX.md", "- [Protocol again](PROTOCOL.md)\n")
	hasErr(t, check(root), "AGENTS.md: memory index block is out of date; run agentbus mem sync")
	if _, err := memory.Sync(root); err != nil {
		t.Fatal(err)
	}
	if r := check(root); len(r.Errors) != 0 {
		t.Fatalf("after sync: %q", r.Errors)
	}
	memtest.Write(t, root, "AGENTS.md", "Read docs/memory/INDEX.md\n")
	hasErr(t, check(root), "AGENTS.md: memory index block is missing; run agentbus mem sync")
}
