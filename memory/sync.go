package memory

import (
	"errors"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"strings"
)

// The generated copy of INDEX.md in AGENTS.md lives between these markers.
const (
	BeginMarker = "<!-- memory-index:begin -->"
	EndMarker   = "<!-- memory-index:end -->"
)

const generatedNote = "<!-- Generated by `agentbus mem sync` from docs/memory/INDEX.md. Edit the index, not this block. -->"

// targetRE is the target of a link or an image.
var targetRE = regexp.MustCompile(`\]\(([^)]+)\)`)

// RenderBlock is the AGENTS.md block for an INDEX.md: its body without the
// title heading, links rebased from docs/memory/ to the repository root.
func RenderBlock(index string) string {
	lines := strings.Split(index, "\n")
	for i, l := range lines {
		if strings.HasPrefix(l, "# ") {
			j := i + 1
			for j < len(lines) && strings.TrimSpace(lines[j]) == "" {
				j++
			}
			lines = append(lines[:i:i], lines[j:]...)
			break
		}
	}
	body := strings.TrimRight(strings.Join(lines, "\n"), " \t\r\n")
	body = targetRE.ReplaceAllStringFunc(body, func(m string) string {
		return "](" + rebase(m[2:len(m)-1]) + ")"
	})
	return BeginMarker + "\n" + generatedNote + "\n\n" + body + "\n" + EndMarker
}

// rebase turns a target relative to docs/memory into one relative to the
// repository root; URLs, anchors and absolute paths are left alone.
func rebase(target string) string {
	if schemeRE.MatchString(target) || strings.HasPrefix(target, "#") || strings.HasPrefix(target, "/") {
		return target
	}
	p, rest := target, ""
	if i := strings.IndexAny(target, "?#"); i >= 0 {
		p, rest = target[:i], target[i:]
	}
	return path.Clean("docs/memory/"+p) + rest
}

// blockSpan locates the marker pair: the begin offset and the end of the end
// marker; ok is false unless both are present in that order.
func blockSpan(text string) (start, end int, ok bool) {
	start = strings.Index(text, BeginMarker)
	if start < 0 {
		return 0, 0, false
	}
	j := strings.Index(text[start:], EndMarker)
	if j < 0 {
		return 0, 0, false
	}
	return start, start + j + len(EndMarker), true
}

// Sync rewrites the block in root/AGENTS.md from root/docs/memory/INDEX.md.
// It writes nothing when the block is already current, and refuses (error)
// when the markers are missing rather than appending a block somewhere.
func Sync(root string) (changed bool, err error) {
	index, err := os.ReadFile(filepath.Join(root, "docs", "memory", "INDEX.md"))
	if err != nil {
		return false, err
	}
	agents := filepath.Join(root, "AGENTS.md")
	b, err := os.ReadFile(agents)
	if err != nil {
		return false, err
	}
	text := string(b)
	start, end, ok := blockSpan(text)
	if !ok {
		return false, errors.New("AGENTS.md: markers " + BeginMarker + " … " + EndMarker + " not found; add them where the index belongs")
	}
	next := text[:start] + RenderBlock(string(index)) + text[end:]
	if next == text {
		return false, nil
	}
	return true, os.WriteFile(agents, []byte(next), 0o644)
}

// blockRule fails when the AGENTS.md block is absent or differs from what
// Sync would write.
func (c *checker) blockRule() {
	index, err1 := os.ReadFile(filepath.Join(c.memory, "INDEX.md"))
	agents, err2 := os.ReadFile(filepath.Join(c.root, "AGENTS.md"))
	if err1 != nil || err2 != nil {
		return // already reported as a missing entry point
	}
	start, end, ok := blockSpan(string(agents))
	switch {
	case !ok:
		c.fail("AGENTS.md: memory index block is missing; run agentbus mem sync")
	case string(agents[start:end]) != RenderBlock(string(index)):
		c.fail("AGENTS.md: memory index block is out of date; run agentbus mem sync")
	}
}
